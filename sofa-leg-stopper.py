"""Create sofa leg stoppers."""
from dataclasses import dataclass
from typing import Callable

import FreeCAD as App
import Draft
import importSVG

def cm(v: float) -> float:
    """Converts mm to cm."""
    return v * 10


def to_object(doc, name: str, objects: list):
    """Create an object from the given name and list of objects."""
    obj = doc.addObject("App::DocumentObjectGroup", name)
    obj.Group = objects
    return obj

@dataclass
class Boundry:
    """Create the boundry of the sheet"""
    width: float
    height: float

    def __call__(self):
        return [
            Draft.make_rectangle(self.width, self.height),
        ]

@dataclass
class Stopper:
    """Create a stopper"""
    long_width: float
    top_width: float
    height: float
    hole_radius: float

    def __call__(self):
        return [
          # Stopper base
          Draft.make_wire(
            [
              App.Vector(self.hole_radius, 0, 0),
              App.Vector(self.top_width / 2, 0, 0),
              App.Vector(self.long_width / 2, -self.height, 0),
              App.Vector(-self.long_width / 2, -self.height, 0),
              App.Vector(-self.top_width / 2, 0, 0),
              App.Vector(-self.hole_radius, 0, 0),
            ],
            closed=False,
          ),
          # Stopper whole
          Draft.make_circle(
            self.hole_radius,
            placement=App.Placement(
              App.Vector(0, 0, 0),
              App.Rotation(0, 0, 1)),
              startangle=180,
              endangle=0,
          ),
        ]


@dataclass
class ConerStopper:
    """Create a corner stopper"""
    top_width: float
    long_width: float
    short_width: float
    height: float
    hole_radius: float

    def __call__(self):
        return [
          # Stopper base
          Draft.make_wire(
            [
              App.Vector(-self.hole_radius, 0, 0),
              App.Vector(-self.top_width / 2, 0, 0),
              App.Vector(-self.long_width / 2, -self.height, 0),
              App.Vector(self.long_width / 2, -self.height, 0),
              App.Vector(self.long_width / 2, self.short_width / 2, 0),
              App.Vector(0, self.top_width / 2, 0),
              App.Vector(0, self.hole_radius, 0),
            ],
            closed=False,
          ),
          # Stopper whole
          Draft.make_circle(
            self.hole_radius,
            placement=App.Placement(
              App.Vector(0, 0, 0),
              App.Rotation(0, 0, 1)),
              startangle=-180,
              endangle=90,
          ),
        ]


@dataclass
class Rotate:
    """Rotates the shape around the given center by the given angle amount."""
    shape: Callable[[], object]
    angle: float
    center: App.Vector
    axis: App.Vector

    def __call__(self):
        return Draft.rotate(self.shape(), self.angle, self.center)

@dataclass
class Move:
    """Move the shape with the given vector."""
    shape: Callable[[], object]
    by: App.Vector

    def __call__(self)-> object:
        return Draft.move(self.shape(), self.by, copy=False)

@dataclass
class ExportToSvg:
    """Exports the given list of objects as SVG."""
    path: str
    export_list:list[Callable[[], object]]

    def __call__(self):
        doc = App.newDocument()
        objects = [to_object(doc, repr(obj), obj())
                  for obj in self.export_list]
        doc.recompute()
        importSVG.export(objects, self.path)


def main():
    """Entry point to the program."""
    long_width, long_height = cm(12), cm(12)
    short_width, short_height = cm(9), cm(8)
    padding, top_width, hole_radius = cm(.5), cm(4), cm(1)

    _ = [svg_document() for svg_document in [
        # Currently Exporting only one SVG file becaues everything fits
        # If needed, multiple SVG files can begenerated by creating ExportToSVG
        # multiple times, giving each a path and a the desired objects.
        ExportToSvg(
          path='./leg-stopper.svg',
          export_list=[
              Boundry(
                  width=cm(30.9),
                  height=cm(30.6),
              ),
              # Corner Stopper
              Move(
                  shape=Rotate(
                      shape=ConerStopper(
                          top_width=top_width,
                          long_width=long_width,
                          short_width=short_width,
                          height=long_height,
                          hole_radius=hole_radius,
                      ),
                      angle=90,
                      center=App.Vector(0, 0, 0),
                      axis=App.Vector(0, 0, 1),
                  ),
                  by=App.Vector(
                      cm(13.5),
                      cm(6.5),
                      0,
                  )
              ),
              # Short Stopper
              Move(
                  shape=Rotate(
                      shape=Stopper(
                          long_width=short_width,
                          top_width=top_width,
                          height=short_height,
                          hole_radius=hole_radius,
                      ),
                      angle=180,
                      center=App.Vector(0, 0, 0),
                      axis=App.Vector(0, 0, 1),
                  ),
                  by=App.Vector(
                      cm(22),
                      cm(17),
                      0,
                  )
              ),
              # Long Stoppers
              *[Move(
                  shape=Rotate(
                    shape=Stopper(
                      long_width=long_width,
                      top_width=top_width,
                      height=long_height,
                      hole_radius=hole_radius,
                    ),
                    angle=angle,
                    center=App.Vector(0, 0, 0),
                    axis=App.Vector(0, 0, 1),
                  ),
                  by=by,
                  ) for (angle, by) in [
                        (0, App.Vector(
                              padding + long_width / 2,
                              padding + long_height,
                              0,
                            )
                        ),
                        (180, App.Vector(
                              padding + long_width / 2,
                              2 * padding + long_height,
                              0,
                            )
                        ),
                        (0, App.Vector(
                              2 * padding + long_height + top_width / 2,
                              2 * padding + 2 * long_height,
                              0,
                            )
                        ),
                    ]
              ],
          ],
        ),
    ]]

if __name__ == "__main__":
    main()
